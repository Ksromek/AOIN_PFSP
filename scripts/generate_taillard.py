_A, _B, _C, _M = 16807, 127773, 2836, 2**31 - 1


def unif(seed: int, low: int, high: int) -> tuple[int, int]:
    """Generator Taillarda (Park-Miller, metoda Schrage'a). Zwraca (wartość, nowe ziarno)."""
    k = seed // _B
    seed = _A * (seed % _B) - k * _C
    if seed < 0:
        seed += _M
    return low + int((seed / _M) * (high - low + 1)), seed


def generate(seed: int, n_jobs: int, n_machines: int) -> np.ndarray:
    """Macierz czasów (maszyny × zadania): maszyna po maszynie, zadanie po zadaniu."""
    p = np.empty((n_machines, n_jobs), dtype=np.int64)
    for i in range(n_machines):
        for j in range(n_jobs):
            p[i, j], seed = unif(seed, 1, 99)
    return p


def write_file(path: Path, n: int, m: int, rows: list[tuple[int, int, int]]) -> None:
    lines = []
    for seed, ub, lb in rows:
        lines.append("number of jobs, number of machines, initial seed, upper bound and lower bound :")
        lines.append(f"{n:12d}{m:12d}{seed:12d}{ub:12d}{lb:12d}")
        lines.append("processing times :")
        for row in generate(seed, n, m):
            lines.append(" " + " ".join(f"{v:2d}" for v in row))
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "data" / "taillard_generated"))
    out = Path(ap.parse_args().out)
    out.mkdir(parents=True, exist_ok=True)
    for (n, m), rows in TAILLARD.items():
        write_file(out / f"tai{n}_{m}.txt", n, m, rows)
    print(f"Zapisano {sum(len(r) for r in TAILLARD.values())} instancji do {out}")


if __name__ == "__main__":
    main()
